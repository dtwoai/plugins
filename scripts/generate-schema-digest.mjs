#!/usr/bin/env node
/**
 * Generates a compact markdown digest from the gateway-config schema artifact
 * and writes it into SKILL.md between sentinel markers.
 *
 * The digest exists because production Claude Code does NOT auto-load a
 * skill's `references/` directory; only SKILL.md is in the cached system
 * prompt. To get field-level schema grounding to real users, the digest
 * must live inline in SKILL.md.
 *
 * Usage:
 *   node scripts/generate-schema-digest.mjs                 # rewrite digest in SKILL.md
 *   node scripts/generate-schema-digest.mjs --check         # CI: exit 1 if digest is stale
 *   node scripts/generate-schema-digest.mjs --schema=PATH --skill=PATH
 *
 * Defaults (relative to repo root):
 *   --schema = dtwo/skills/dtwo-gateway-config/schema-reference.json
 *   --skill  = dtwo/skills/dtwo-gateway-config/SKILL.md
 *
 * Determinism: output is a pure function of the input artifact. Running
 * twice on the same input produces byte-identical SKILL.md content.
 *
 * Coverage: `assertDigestCoverage` runs before write-out AND before the
 * `--check` comparison, so a user-audience field whose `target` never makes
 * it into the rendered digest fails the generator rather than silently
 * disappearing. It keys on `target` (unique across the artifact) rather than
 * on field name (which collides across sections), and matches the
 * backtick-delimited form (several targets are proper substrings of others).
 */

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const BEGIN_MARKER = '<!-- BEGIN SCHEMA DIGEST (generated by scripts/generate-schema-digest.mjs — do not edit by hand) -->';
const END_MARKER = '<!-- END SCHEMA DIGEST -->';
const DEFAULT_SCHEMA = 'dtwo/skills/dtwo-gateway-config/schema-reference.json';
const DEFAULT_SKILL = 'dtwo/skills/dtwo-gateway-config/SKILL.md';

function parseArgs(argv) {
  const out = { check: false, schema: DEFAULT_SCHEMA, skill: DEFAULT_SKILL };
  for (const a of argv) {
    if (a === '--check') out.check = true;
    else if (a.startsWith('--schema=')) out.schema = a.slice('--schema='.length);
    else if (a.startsWith('--skill=')) out.skill = a.slice('--skill='.length);
    else if (a === '--help' || a === '-h') {
      console.log(
        [
          'Usage: node scripts/generate-schema-digest.mjs [--check] [--schema=PATH] [--skill=PATH]',
          '',
          '  --check          Exit 1 if SKILL.md digest is stale (does not write).',
          '  --schema=PATH    Override default schema path.',
          '  --skill=PATH     Override default SKILL.md path.',
        ].join('\n'),
      );
      process.exit(0);
    } else {
      console.error(`Unknown argument: ${a}`);
      process.exit(2);
    }
  }
  return out;
}

// --- audience filter (mirrors d2-skill-harness audienceFilter.ts) -----------

function hasDescendantSection(sectionPath, allSections) {
  if (sectionPath === '') return false;
  const prefix = `${sectionPath}.`;
  for (const s of allSections) {
    if (s.path !== sectionPath && s.path.startsWith(prefix)) return true;
  }
  return false;
}

function filterArtifactForSkill(artifact) {
  const copy = structuredClone(artifact);
  const keptSections = [];
  for (const section of copy.sections) {
    const filteredFields = section.fields.filter(f => f.audience === 'user');
    const hasVariants = Array.isArray(section.variants) && section.variants.length > 0;
    const hasDescendants = hasDescendantSection(section.path, copy.sections);
    const keepEmpty = hasVariants || hasDescendants || section.path === '';
    if (filteredFields.length === 0 && !keepEmpty) continue;
    keptSections.push({ ...section, fields: filteredFields });
  }
  return { ...copy, sections: keptSections };
}

// --- helpers ---------------------------------------------------------------

function findSection(filtered, path) {
  const s = filtered.sections.find(x => x.path === path);
  if (!s) throw new Error(`Missing section in filtered artifact: ${path}`);
  return s;
}

function fieldByName(section, name) {
  return section.fields.find(f => f.name === name);
}

function enumList(field) {
  if (!field?.enumValues) return '';
  return field.enumValues.map(v => `\`${v}\``).join('/');
}

function tickQuotes(s) {
  // Convert "identifier" → `identifier` in artifact-provided constraint
  // messages so they render as code in markdown. Conservative: only single-
  // word identifiers (no spaces).
  return s.replace(/"([A-Za-z0-9_]+)"/g, '`$1`');
}

function escapePipe(s) {
  return String(s).replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
}

function renderConstraints(constraints) {
  if (!Array.isArray(constraints) || constraints.length === 0) return '';
  return constraints
    .map(c => `> ${tickQuotes(c.message ?? '')}`)
    .join('\n>\n');
}

function constraintHeading(constraints) {
  const n = Array.isArray(constraints) ? constraints.length : 0;
  return `**Cross-field constraint${n === 1 ? '' : 's'}** (verbatim from artifact):`;
}

function typeCell(field) {
  return field.enumValues ? `enum: ${enumList(field)}` : field.type;
}

/**
 * Default cell for the generic field tables. See `DEFAULT_COLUMN_LEGEND` —
 * the two must stay in step.
 *
 * Load-bearing: when an OPTIONAL field declares neither default the cell says
 * `gateway-owned`, never `—`. The promoted security-posture booleans
 * (`jwt_issuer_verification` and friends) are exactly this case, and "no
 * default" would be a dangerous thing to imply about them — the gateway does
 * apply a default, it just does not travel in the artifact.
 *
 * A REQUIRED field with neither default is the opposite case and renders `—`.
 * A required field has no default by definition: if the gateway supplied one
 * at boot, the field would not be required. Calling it `gateway-owned` would
 * tell the reader they may omit it, which is exactly wrong.
 */
function defaultCell(field) {
  if (field.schemaDefault !== null && field.schemaDefault !== undefined) {
    return `\`${JSON.stringify(field.schemaDefault)}\` (schema)`;
  }
  if (field.deployDefault !== null && field.deployDefault !== undefined) {
    return `\`${JSON.stringify(field.deployDefault)}\` (deploy)`;
  }
  return field.required ? '—' : '`gateway-owned`';
}

/**
 * Emitted once, ahead of every table that carries a `Default` column, so a
 * reader who lands directly on a later section (`session_control`, say) does
 * not have to guess what `gateway-owned` means.
 */
const DEFAULT_COLUMN_LEGEND =
  'Reading the **`Default`** column in the tables below: `` `value` (schema) `` and `` `value` (deploy) `` are defaults the artifact declares. **`gateway-owned`** marks an optional field whose default the gateway applies at boot — the artifact does not declare it, so it is **not** the same as having no default; omitting the field is safe. **`—`** marks a required field, which has no default by definition — you must supply a value.';

/** Shared generic table over every (already audience-filtered) field. */
function fieldTableLines(section) {
  const rows = section.fields.map(f => {
    const req = f.required ? 'yes' : 'no';
    const target = f.target ? `\`${f.target}\`` : '—';
    const guidance = escapePipe(tickQuotes(f.rationale ?? f.description ?? ''));
    return `| \`${f.name}\` | ${req} | ${escapePipe(typeCell(f))} | ${defaultCell(f)} | ${target} | ${guidance} |`;
  });
  return [
    '| Field | Required | Type | Default | Target | Guidance (from artifact) |',
    '|---|---|---|---|---|---|',
    ...rows,
  ];
}

/** Generic section block: heading, artifact description, table, constraints. */
function renderGenericSection(filtered, path, heading) {
  const section = findSection(filtered, path);
  const lines = [heading, ''];
  if (section.description) {
    lines.push(String(section.description).replace(/\r?\n/g, ' '), '');
  }
  lines.push(...fieldTableLines(section), '');
  const constraintBlock = renderConstraints(section.crossFieldConstraints);
  if (constraintBlock) {
    lines.push(constraintHeading(section.crossFieldConstraints), constraintBlock, '');
  }
  return lines.join('\n');
}

function jwksAllRequired(jwks) {
  return jwks.fields.length > 0 && jwks.fields.every(f => f.required);
}

